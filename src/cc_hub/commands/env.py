# -*- coding: utf-8 -*-
"""cc-hub env: probe this machine and write ENV.md / env.json for the agent."""

from __future__ import annotations

import json
import locale
import os
import platform as pyplatform
import shutil
import subprocess
import time
from collections.abc import Callable
from datetime import datetime
from pathlib import Path

import psutil
import typer

from cc_hub.encoding import decode_bytes, write_text
from cc_hub.hub import load_config
from cc_hub.platform import is_windows, is_wsl, which_minimal

PROBE_BINARIES = ("cc-hub", "uv", "python", "cc-connect", "claude", "codex")
SHELLS = ("bash", "zsh", "pwsh", "powershell", "cmd")
CC_CONNECT_CONFIGS = (".cc-connect/config.toml",)


def version_of(exe: str, *, run: Callable = subprocess.run) -> str:
    try:
        proc = run([exe, "--version"], capture_output=True, timeout=5)
    except (OSError, subprocess.SubprocessError):
        return ""
    lines = decode_bytes(proc.stdout or proc.stderr or b"").strip().splitlines()
    return lines[0][:80] if lines else ""


def probe(
    hub: Path,
    *,
    tools: list[str],
    home: Path | None = None,
    which: Callable[[str], str | None] = shutil.which,
    which_daemon: Callable[[str], str | None] = which_minimal,
    version_of: Callable[[str], str] = version_of,
    now: datetime | None = None,
) -> dict:
    hub = Path(hub)
    home = home or Path.home()
    now = now or datetime.now().astimezone()
    shells = {name: which(name) for name in SHELLS}
    shells["default"] = os.environ.get("SHELL") or (
        "powershell" if is_windows() else "sh"
    )
    cc_cfg = next(
        (str(home / rel) for rel in CC_CONNECT_CONFIGS if (home / rel).is_file()),
        None,
    )
    return {
        "generated_at": now.isoformat(timespec="seconds"),
        "hub": str(hub),
        "system": {
            "os": pyplatform.system(),
            "release": pyplatform.release(),
            "arch": pyplatform.machine(),
            "wsl": is_wsl(),
            "home": str(home),
            "timezone": time.tzname[0],
            "locale_encoding": locale.getpreferredencoding(False),
            "pythonutf8": os.environ.get("PYTHONUTF8", ""),
        },
        "shells": shells,
        "tools": {
            name: {
                "path": which(name),
                "version": version_of(name) if which(name) else "",
            }
            for name in tools
        },
        "agents": {
            "claude_home": (home / ".claude").is_dir(),
            "codex_home": (home / ".codex").is_dir(),
            "cc_connect_config": cc_cfg,
        },
        "paths": {
            name: {
                "path": which(name),
                "daemon_visible": which_daemon(name) is not None,
            }
            for name in PROBE_BINARIES
        },
        "resources": {
            "cpus": os.cpu_count() or 1,
            "memory_gb": round(psutil.virtual_memory().total / 2**30, 1),
            "disk_free_gb": round(shutil.disk_usage(hub).free / 2**30, 1),
        },
    }


def render_env_md(data: dict) -> str:
    s = data["system"]
    lines = [
        "# Environment",
        "",
        f"Generated by `cc-hub env` at {data['generated_at']}. "
        "Re-run when in doubt.",
        "",
        "## System",
        "",
        f"- OS: {s['os']} {s['release']} ({s['arch']})"
        f"{' under WSL' if s['wsl'] else ''}",
        f"- Home: {s['home']}",
        f"- Hub: {data['hub']}",
        f"- Timezone: {s['timezone']}; locale encoding: "
        f"{s['locale_encoding']}; PYTHONUTF8="
        f"{s['pythonutf8'] or 'unset'}",
        "",
        "## Shell",
        "",
        f"- Default shell: {data['shells']['default']}",
    ]
    for name in SHELLS:
        path = data["shells"].get(name)
        lines.append(f"- {name}: {path or 'not installed'}")
    lines += ["", "## Tools", ""]
    for name, info in data["tools"].items():
        if info["path"]:
            lines.append(f"- {name}: {info['path']} {info['version']}".rstrip())
        else:
            lines.append(f"- {name}: not installed")
    a = data["agents"]
    lines += [
        "",
        "## Agents & bridge",
        "",
        f"- ~/.claude present: {a['claude_home']}",
        f"- ~/.codex present: {a['codex_home']}",
        f"- cc-connect config: {a['cc_connect_config'] or 'not found'}",
        "",
        "## Paths",
        "",
        "Absolute paths to use when a command is not found on PATH:",
        "",
    ]
    for name, info in data["paths"].items():
        if not info["path"]:
            lines.append(f"- {name}: not installed")
        elif info["daemon_visible"]:
            lines.append(f"- {name}: {info['path']}")
        else:
            lines.append(
                f"- {name}: {info['path']} "
                "(not visible to daemons with a minimal PATH)"
            )
    r = data["resources"]
    lines += [
        "",
        "## Resources",
        "",
        f"- CPUs: {r['cpus']}; memory: {r['memory_gb']} GB; "
        f"free disk at hub: {r['disk_free_gb']} GB",
        "",
    ]
    return "\n".join(lines)


def write_env(hub: Path, **probe_kwargs) -> dict:
    hub = Path(hub)
    if "tools" not in probe_kwargs:
        probe_kwargs["tools"] = list(
            load_config(hub).get("env", {}).get("tools", [])
        )
    data = probe(hub, **probe_kwargs)
    write_text(
        hub / "env.json",
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
    )
    write_text(hub / "ENV.md", render_env_md(data))
    return data


def register(app: typer.Typer) -> None:
    @app.command("env")
    def env_cmd(
        ctx: typer.Context,
        as_json: bool = typer.Option(
            False, "--json", help="Print env.json to stdout."
        ),
    ) -> None:
        """Probe this machine and write ENV.md and env.json."""
        from cc_hub.console import echo_json, resolve_hub

        hub = resolve_hub(ctx)
        data = write_env(hub)
        if as_json:
            echo_json(data)
        else:
            typer.echo(f"wrote {hub / 'ENV.md'} and {hub / 'env.json'}")
